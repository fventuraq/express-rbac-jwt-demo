CREATE TABLE ROLES (
    RolID SERIAL PRIMARY KEY,
    RolNom VARCHAR(100) NOT NULL,
    CreDat TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CreByID INT,
    UpdDat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdByID INT,
    EstReg CHAR(1) DEFAULT 'A'
);

CREATE TABLE FUNCIONES (
    FunID SERIAL PRIMARY KEY,
    FunNom VARCHAR(100) NOT NULL,
    CreDat TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CreByID INT,
    UpdDat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdByID INT,
    EstReg CHAR(1) DEFAULT 'A'
);

CREATE TABLE ROL_FUN (
    RolID INT NOT NULL,
    FunID INT NOT NULL,
    PRIMARY KEY (RolID, FunID),
    CONSTRAINT fk_rol FOREIGN KEY (RolID) REFERENCES ROLES(RolID),
    CONSTRAINT fk_fun FOREIGN KEY (FunID) REFERENCES FUNCIONES(FunID)
);

 CREATE TABLE VIEWS (
    VieID SERIAL PRIMARY KEY,
    VieNom VARCHAR(255) NOT NULL,
    VieURL VARCHAR(255) NOT NULL,
    VieCtr VARCHAR(100) NOT NULL,
    VieIco VARCHAR(100),
    VieEst VARCHAR(10) CHECK (VieEst IN ('ACTIVO', 'INACTIVO')) NOT NULL,
    VieEstVis BOOLEAN DEFAULT TRUE,
    CreDat TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CreByID INT,
    UpdDat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdByID INT,
    EstReg CHAR(1) DEFAULT 'A'
);


CREATE TABLE VIEW_FUNCION (
    VieID INT NOT NULL,
    FunID INT NOT NULL,
    PRIMARY KEY (VieID, FunID),
    CONSTRAINT fk_view_funcion_view FOREIGN KEY (VieID) REFERENCES VIEWS(VieID) ON DELETE CASCADE,
    CONSTRAINT fk_view_funcion_funcion FOREIGN KEY (FunID) REFERENCES FUNCIONES(FunID) ON DELETE CASCADE
); 

CREATE TABLE PERSON (
    PerID SERIAL PRIMARY KEY,
    PerNam VARCHAR(100) NOT NULL,
    PerSur VARCHAR(100) NOT NULL,
    PerCPF VARCHAR(11) UNIQUE NOT NULL,
    PerPho VARCHAR(20),
    PerEma VARCHAR(255),
    CreDat TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CreByID INT,
    UpdDat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdByID INT,
    EstReg CHAR(1) DEFAULT 'A'
); 

CREATE TABLE USUARIOS (
    UsuID SERIAL PRIMARY KEY,
    RolID INT NOT NULL,
    PerID INT NOT NULL UNIQUE,
    UsuNam VARCHAR(32) NOT NULL UNIQUE,
    UsuPas TEXT NOT NULL,
    CONSTRAINT fk_persona FOREIGN KEY (PerID) REFERENCES PERSON(PerID) ON DELETE CASCADE, 
    CONSTRAINT fk_rol FOREIGN KEY (RolID) REFERENCES ROLES(RolID) ON DELETE CASCADE
);